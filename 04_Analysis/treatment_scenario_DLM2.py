X_CR_full  = X_CR.merge(y, left_index=True, right_index=True)
X_mol_full = X_molecular_features.merge(y, left_index=True, right_index=True)

# Base component models — used only to produce raw risk scores
with open(CR_ESTIMATOR, 'rb') as f:
    base_CR_model = pickle.load(f)
with open(MOL_ESTIMATOR, 'rb') as f:
    base_mol_model = pickle.load(f)

# Original fusion model and scalers — scalers used throughout for
# point estimates; original fusion model retained only for threshold parsing
with open(FUSION_MODEL, 'rb') as f:
    original_fusion_model = pickle.load(f)
with open(FUSION_SCALERS, 'rb') as f:
    all_scalers = pickle.load(f)

original_scaler_CR  = all_scalers['Clinical-ResNet']
original_scaler_mol = all_scalers['Molecular']

fusion_threshold = parse_fusion_threshold(FUSION_THRESHOLD_FILE)
if fusion_threshold is None:
    print("  Threshold not found — will recompute on refit scale after fitting refit model")
else:
    print(f"  Fusion threshold (from file): {fusion_threshold:.6f}")

# =============================================================================
# STEP 2: PATIENT INTERSECTIONS
# =============================================================================

print("\nStep 2: Finding patient intersections...")

CR_discovery_ids  = set(X_CR_full[X_CR_full['Cohort'] == 'Discovery'].index)
CR_replicate_ids  = set(X_CR_full[X_CR_full['Cohort'] == 'Replicate'].index)
mol_discovery_ids = set(X_mol_full[X_mol_full['Cohort'] == 'Discovery'].index)
mol_replicate_ids = set(X_mol_full[X_mol_full['Cohort'] == 'Replicate'].index)

discovery_intersection = sorted(CR_discovery_ids & mol_discovery_ids)
replicate_intersection  = sorted(CR_replicate_ids  & mol_replicate_ids)

print(f"  Discovery intersection: {len(discovery_intersection)} patients")
print(f"  Replicate intersection: {len(replicate_intersection)} patients")

drop_cols = ['Progression Free Survival', 'Event', 'Cohort']
X_CR_discovery  = X_CR_full.loc[discovery_intersection].drop(columns=drop_cols)
X_CR_replicate  = X_CR_full.loc[replicate_intersection].drop(columns=drop_cols)
X_mol_discovery = X_mol_full.loc[discovery_intersection].drop(columns=drop_cols)
X_mol_replicate = X_mol_full.loc[replicate_intersection].drop(columns=drop_cols)

y_discovery_full = y.loc[discovery_intersection, ['Progression Free Survival', 'Event']]
y_replicate_full = y.loc[replicate_intersection,  ['Progression Free Survival', 'Event']]
y_discovery      = create_structured_outcomes(y_discovery_full)
y_replicate      = create_structured_outcomes(y_replicate_full)

# Pre-compute raw risk scores for all patients (base models are fixed)
cr_disc_risks_raw  = base_CR_model.predict(X_CR_discovery.values)
mol_disc_risks_raw = base_mol_model.predict(X_mol_discovery.values)
cr_rep_risks_raw   = base_CR_model.predict(X_CR_replicate.values)
mol_rep_risks_raw  = base_mol_model.predict(X_mol_replicate.values)

# =============================================================================
# STEP 3: REFIT FUSION MODEL ON FULL DISCOVERY SET
# =============================================================================
# This is the deployment estimator for all point estimates. It uses the
# original scalers (same as training) and alpha=0 to remove LASSO shrinkage
# bias. The threshold is recomputed on this scale so everything is consistent.

print("\nStep 3: Fitting refit fusion model on full discovery set...")

cr_disc_scaled  = original_scaler_CR.transform(cr_disc_risks_raw.reshape(-1, 1)).flatten()
mol_disc_scaled = original_scaler_mol.transform(mol_disc_risks_raw.reshape(-1, 1)).flatten()
X_fusion_disc   = np.column_stack([cr_disc_scaled, mol_disc_scaled])

refit_fusion_model = CoxPHSurvivalAnalysis(alpha=0.0, verbose=0)
refit_fusion_model.fit(X_fusion_disc, y_discovery)
print(f"  Refit fusion CoxPH fitted on {len(discovery_intersection)} discovery patients")

# Recompute threshold on refit scale (median discovery risk)
refit_disc_scores = refit_fusion_model.predict(X_fusion_disc)
fusion_threshold  = float(np.median(refit_disc_scores))
print(f"  Risk threshold (refit-scale median discovery risk): {fusion_threshold:.6f}")

cr_rep_scaled   = original_scaler_CR.transform(cr_rep_risks_raw.reshape(-1, 1)).flatten()
mol_rep_scaled  = original_scaler_mol.transform(mol_rep_risks_raw.reshape(-1, 1)).flatten()
X_fusion_rep    = np.column_stack([cr_rep_scaled, mol_rep_scaled])
refit_pred_rep  = refit_fusion_model.predict(X_fusion_rep)

harrell_disc = concordance_index_censored(
    y_discovery['Event'], y_discovery['Progression Free Survival'], refit_disc_scores)[0]
harrell_rep  = concordance_index_censored(
    y_replicate['Event'], y_replicate['Progression Free Survival'], refit_pred_rep)[0]
print(f"  Refit fusion CoxPH — Harrell C: Discovery={harrell_disc:.4f}  Replicate={harrell_rep:.4f}")

# =============================================================================
# STEP 4: BOOTSTRAP UNCERTAINTY QUANTIFICATION
# =============================================================================
# Each bootstrap entry stores its own scaler pair alongside the fitted model.
# This ensures that at inference time each entry scales the raw risk scores
# with the same distribution it was trained on — fully consistent.

print("\nStep 4: Bootstrap uncertainty quantification...")
print("  Each bootstrap entry stores model + scaler pair for consistent inference.")

np.random.seed(RANDOM_SEED)
bootstrap_entries  = []   # list of {'model', 'scaler_cr', 'scaler_mol'}
bootstrap_metadata = []
start_time = time.time()

for i in range(N_BOOTSTRAP):
    iter_start = time.time()
    print(f"  [{i+1}/{N_BOOTSTRAP}] Bootstrap iteration {i+1}...", end='', flush=True)

    try:
        indices = np.random.choice(len(discovery_intersection), len(discovery_intersection), replace=True)

        cr_boot_raw  = cr_disc_risks_raw[indices]
        mol_boot_raw = mol_disc_risks_raw[indices]

        # Refit scaler on this bootstrap sample
        scaler_cr_b  = StandardScaler().fit(cr_boot_raw.reshape(-1, 1))
        scaler_mol_b = StandardScaler().fit(mol_boot_raw.reshape(-1, 1))

        cr_boot_scaled  = scaler_cr_b.transform(cr_boot_raw.reshape(-1, 1)).flatten()
        mol_boot_scaled = scaler_mol_b.transform(mol_boot_raw.reshape(-1, 1)).flatten()
        X_fusion_boot   = np.column_stack([cr_boot_scaled, mol_boot_scaled])

        y_boot = y_discovery[indices]

        boot_model = CoxPHSurvivalAnalysis(alpha=0.0, verbose=0)
        boot_model.fit(X_fusion_boot, y_boot)

        # Store model AND scalers together — inseparable for correct inference
        bootstrap_entries.append({
            'model':      boot_model,
            'scaler_cr':  scaler_cr_b,
            'scaler_mol': scaler_mol_b,
        })

        bootstrap_metadata.append({
            'iteration':        i + 1,
            'n_samples':        len(indices),
            'n_unique_samples': len(np.unique(indices)),
            'CR_weight':        boot_model.coef_[0],
            'Mol_weight':       boot_model.coef_[1],
            'cr_scaler_mean':   scaler_cr_b.mean_[0],
            'cr_scaler_std':    scaler_cr_b.scale_[0],
            'mol_scaler_mean':  scaler_mol_b.mean_[0],
            'mol_scaler_std':   scaler_mol_b.scale_[0],
            'converged':        True,
        })

        iter_time = time.time() - iter_start
        print(f" OK ({iter_time:.1f}s, CR={boot_model.coef_[0]:.3f}, Mol={boot_model.coef_[1]:.3f})", flush=True)

        if (i + 1) % 10 == 0 or (i + 1) == N_BOOTSTRAP:
            pd.DataFrame(bootstrap_metadata).to_csv(BOOTSTRAP_DIR / 'bootstrap_metadata.csv', index=False)

    except Exception as e:
        print(f" ERROR: {str(e)}", flush=True)
        bootstrap_metadata.append({'iteration': i + 1, 'converged': False, 'error': str(e)})

elapsed = time.time() - start_time
print(f"\n  Bootstrap completed in {elapsed/60:.1f} minutes")
print(f"  Successful iterations: {len(bootstrap_entries)}/{N_BOOTSTRAP}")

