def create_structured_outcomes(df):
    return np.array(
        [(bool(e), float(t)) for e, t in zip(df['Event'], df['Progression Free Survival'])],
        dtype=[("Event", bool), ("Progression Free Survival", float)]
    )


def parse_fusion_threshold(filepath):
    try:
        with open(filepath, 'r') as f:
            for line in f:
                if 'Fusion threshold' in line and ':' in line:
                    return float(line.split(':')[1].strip())
    except Exception as e:
        print(f"  Could not parse threshold: {e}")
    return None


def _fusion_survival_curve(model, cr_risk_scaled, mol_risk_scaled, time_points):
    """Predict survival curve from a fitted fusion model given pre-scaled inputs."""
    fusion_input = np.array([[cr_risk_scaled, mol_risk_scaled]])
    surv_fn = model.predict_survival_function(fusion_input)[0]
    if hasattr(surv_fn, 'x') and len(surv_fn.x) > 0:
        t_min, t_max = surv_fn.x[0], surv_fn.x[-1]
    else:
        t_min, t_max = 0, 200
    return np.array([surv_fn(np.clip(t, t_min, t_max)) for t in time_points])


def get_fusion_survival_curves_with_uncertainty(cr_risk_raw, mol_risk_raw,
                                                refit_fusion_model,
                                                original_scaler_CR,
                                                original_scaler_mol,
                                                bootstrap_entries,
                                                time_points):
    """
    Point estimate from refit_fusion_model using original scalers.
    95% CI from 2.5th-97.5th percentiles of bootstrap survival curves,
    where each bootstrap entry applies its own scaler before predicting.
    Both use raw risk scores as input so scaling is handled internally,
    ensuring consistency within each model.
    """
    # Point estimate — original scalers + refit model
    cr_scaled_point  = original_scaler_CR.transform([[cr_risk_raw]])[0][0]
    mol_scaled_point = original_scaler_mol.transform([[mol_risk_raw]])[0][0]
    point_curve = _fusion_survival_curve(
        refit_fusion_model, cr_scaled_point, mol_scaled_point, time_points)

    # Bootstrap curves — each entry uses its own scaler for consistency
    boot_curves = []
    for entry in bootstrap_entries:
        cr_sc  = entry['scaler_cr'].transform([[cr_risk_raw]])[0][0]
        mol_sc = entry['scaler_mol'].transform([[mol_risk_raw]])[0][0]
        boot_curves.append(
            _fusion_survival_curve(entry['model'], cr_sc, mol_sc, time_points))
    boot_curves = np.array(boot_curves)

    return {
        'point':    point_curve,
        'ci_lower': np.percentile(boot_curves, 2.5,  axis=0),
        'ci_upper': np.percentile(boot_curves, 97.5, axis=0),
    }


def generate_fusion_treatment_scenarios(patient_id, X_CR, X_mol,
                                        base_CR_model, base_mol_model,
                                        refit_fusion_model,
                                        original_scaler_CR, original_scaler_mol,
                                        fusion_threshold):
    """Risk score + risk group per scenario using the refit fusion estimator."""
    cr_features  = X_CR.loc[patient_id].copy()
    mol_features = X_mol.loc[patient_id].copy()

    mol_risk_raw    = base_mol_model.predict([mol_features.values])[0]
    mol_risk_scaled = original_scaler_mol.transform([[mol_risk_raw]])[0][0]

    results = []
    for scenario in TREATMENT_SCENARIOS:
        sf = cr_features.copy()
        sf['Extent of Tumor Resection'] = scenario['resection']
        sf['Chemotherapy']              = scenario['chemo']

        cr_risk_raw    = base_CR_model.predict([sf.values])[0]
        cr_risk_scaled = original_scaler_CR.transform([[cr_risk_raw]])[0][0]

        fusion_input = np.array([[cr_risk_scaled, mol_risk_scaled]])
        fusion_risk  = float(refit_fusion_model.predict(fusion_input)[0])
        risk_group   = 'High' if fusion_risk > fusion_threshold else 'Low'

        results.append({
            'Patient_ID':      patient_id,
            'Treatment_Label': scenario['label'],
            'Resection':       scenario['label'].split(' + ')[0],
            'Chemotherapy':    'Yes' if scenario['chemo'] == 1 else 'No',
            'CR_Risk_Raw':     base_CR_model.predict([sf.values])[0],
            'Mol_Risk_Raw':    mol_risk_raw,
            'Fusion_Risk':     fusion_risk,
            'Risk_Group':      risk_group,
        })

    return pd.DataFrame(results)


def plot_fusion_patient_survival_scenarios(patient_id, X_CR, X_mol,
                                           base_CR_model, base_mol_model,
                                           refit_fusion_model,
                                           bootstrap_entries,
                                           original_scaler_CR, original_scaler_mol,
                                           fusion_threshold, save_path,
                                           actual_pfs=None, actual_event=None):
    cr_features  = X_CR.loc[patient_id].copy()
    mol_features = X_mol.loc[patient_id].copy()

    # Use refit model to determine time axis
    cr_risk_raw_base    = base_CR_model.predict([cr_features.values])[0]
    mol_risk_raw_base   = base_mol_model.predict([mol_features.values])[0]
    cr_scaled_base      = original_scaler_CR.transform([[cr_risk_raw_base]])[0][0]
    mol_scaled_base     = original_scaler_mol.transform([[mol_risk_raw_base]])[0][0]

    test_surv_fn = refit_fusion_model.predict_survival_function(
        np.array([[cr_scaled_base, mol_scaled_base]]))[0]
    if hasattr(test_surv_fn, 'x') and len(test_surv_fn.x) > 0:
        min_time, max_time = test_surv_fn.x[0], test_surv_fn.x[-1]
    else:
        min_time, max_time = 0, 150

    time_points = np.linspace(min_time, max_time, 100)

    fig, axes = plt.subplots(1, 2, figsize=(16, 6))
    ax1 = axes[0]
    scenario_data = []

    # Molecular risk is fixed across scenarios (only CR features vary with treatment)
    mol_risk_raw = base_mol_model.predict([mol_features.values])[0]

    for scenario in TREATMENT_SCENARIOS:
        sf = cr_features.copy()
        sf['Extent of Tumor Resection'] = scenario['resection']
        sf['Chemotherapy']              = scenario['chemo']

        cr_risk_raw = base_CR_model.predict([sf.values])[0]

        # Survival curves: point from refit model, CI from bootstrap percentiles.
        # Each bootstrap entry scales with its own scaler — fully consistent.
        surv_stats = get_fusion_survival_curves_with_uncertainty(
            cr_risk_raw, mol_risk_raw,
            refit_fusion_model,
            original_scaler_CR, original_scaler_mol,
            bootstrap_entries, time_points)

        # Risk score: point from refit model; CI from bootstrap percentiles.
        # Same model family and scale — point estimate always within its CI.
        cr_risk_scaled  = original_scaler_CR.transform([[cr_risk_raw]])[0][0]
        mol_risk_scaled = original_scaler_mol.transform([[mol_risk_raw]])[0][0]
        fusion_input    = np.array([[cr_risk_scaled, mol_risk_scaled]])
        fusion_risk     = float(refit_fusion_model.predict(fusion_input)[0])

        boot_fusion_risks = np.array([
            entry['model'].predict(
                np.array([[
                    entry['scaler_cr'].transform([[cr_risk_raw]])[0][0],
                    entry['scaler_mol'].transform([[mol_risk_raw]])[0][0],
                ]])
            )[0]
            for entry in bootstrap_entries
        ])
        fusion_risk_ci_lower = float(np.percentile(boot_fusion_risks, 2.5))
        fusion_risk_ci_upper = float(np.percentile(boot_fusion_risks, 97.5))
        risk_group = 'High' if fusion_risk > fusion_threshold else 'Low'

        ax1.plot(time_points, surv_stats['point'],
                 color=scenario['color'], linestyle=scenario['linestyle'],
                 linewidth=2.5, label=scenario['label'], alpha=0.9)
        ax1.fill_between(time_points, surv_stats['ci_lower'], surv_stats['ci_upper'],
                         color=scenario['color'], alpha=0.15)

        # Survival at 1, 3, 5 years with 95% CI
        row = {
            'scenario':             scenario['label'],
            'fusion_risk':          fusion_risk,
            'fusion_risk_ci_lower': fusion_risk_ci_lower,
            'fusion_risk_ci_upper': fusion_risk_ci_upper,
            'risk_group':           risk_group,
        }
        for t_months, t_label in zip(SURV_TIME_POINTS, SURV_LABELS):
            if max_time >= t_months:
                idx = np.argmin(np.abs(time_points - t_months))
                row[t_label]               = surv_stats['point'][idx]
                row[f'{t_label}_ci_lower'] = surv_stats['ci_lower'][idx]
                row[f'{t_label}_ci_upper'] = surv_stats['ci_upper'][idx]
            else:
                row[t_label]               = None
                row[f'{t_label}_ci_lower'] = None
                row[f'{t_label}_ci_upper'] = None
        scenario_data.append(row)

    if actual_pfs is not None and actual_event is not None and actual_pfs <= max_time:
        if actual_event:
            ax1.axvline(actual_pfs, color='black', linestyle=':', linewidth=2.5,
                        label=f'Actual Progression ({actual_pfs:.1f} mo)', zorder=1, alpha=0.7)
        else:
            ax1.axvline(actual_pfs, color='gray', linestyle=':', linewidth=2.5,
                        label=f'Censored at {actual_pfs:.1f} mo', zorder=1, alpha=0.7)

    ax1.set_xlabel('Time (months)', fontsize=12, fontweight='bold')
    ax1.set_ylabel('Progression-Free Survival Probability', fontsize=12, fontweight='bold')
    ax1.set_title(f'Patient {patient_id}: Fusion Model (ResNet + Molecular)\nSurvival Curves Under Treatment Scenarios',
                  fontsize=14, fontweight='bold')
    ax1.legend(loc='lower left', fontsize=9, framealpha=0.95)
    ax1.grid(alpha=0.3)
    ax1.set_ylim(0, 1.05)
    ax1.set_xlim(0, max_time)

    # Table
    ax2 = axes[1]
    ax2.axis('off')

    scenario_df = pd.DataFrame(scenario_data)
    headers = ['Treatment Scenario', 'Fusion Risk\n(95% CI)', 'Risk\nGroup']
    for t_label in SURV_LABELS:
        if scenario_df[t_label].notna().any():
            headers.append(t_label.replace('yr', '-yr PFS\n(95% CI)'))

    table_data = []
    for _, row in scenario_df.iterrows():
        rd = [
            row['scenario'],
            f"{row['fusion_risk']:.2f}\n[{row['fusion_risk_ci_lower']:.2f}, {row['fusion_risk_ci_upper']:.2f}]",
            row['risk_group'],
        ]
        for t_label in SURV_LABELS:
            if row[t_label] is not None:
                rd.append(
                    f"{row[t_label]:.2f}\n"
                    f"[{row[f'{t_label}_ci_lower']:.2f}, {row[f'{t_label}_ci_upper']:.2f}]"
                )
            else:
                rd.append("N/A")
        table_data.append(rd)

    table = ax2.table(cellText=table_data, colLabels=headers,
                      cellLoc='center', loc='center',
                      colWidths=[0.35, 0.15, 0.15] + [0.12] * (len(headers) - 3))
    table.auto_set_font_size(False)
    table.set_fontsize(9)
    table.scale(1, 3.2)

    for j in range(len(headers)):
        table[(0, j)].set_facecolor('#1a9850')
        table[(0, j)].set_text_props(weight='bold', color='white')

    for i in range(1, len(table_data) + 1):
        if i % 2 == 0:
            for j in range(len(headers)):
                table[(i, j)].set_facecolor('#f0f0f0')
        table[(i, 2)].set_facecolor('#ffcccc' if table_data[i-1][2] == 'High' else '#ccffcc')

    ax2.set_title(
        'Treatment Scenario Summary\n'
        'Point estimate from full-discovery refit; 95% CI = 2.5th–97.5th bootstrap percentile',
        fontsize=9, fontweight='bold', pad=20)

    if actual_pfs is not None and actual_event is not None:
        status = "Progressed" if actual_event else "Censored"
        fig.suptitle(f'Fusion Model Analysis for Patient {patient_id}\n'
                     f'Actual outcome: {status} at {actual_pfs:.1f} months',
                     fontsize=14, fontweight='bold', y=0.98)
    else:
        fig.suptitle(f'Fusion Model Analysis for Patient {patient_id}',
                     fontsize=14, fontweight='bold', y=0.98)

    plt.tight_layout()
    plt.savefig(save_path, dpi=300, bbox_inches='tight')
    plt.close()

    return scenario_df


