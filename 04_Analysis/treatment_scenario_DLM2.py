"""
Treatment Projection Analysis - Late Fusion Model (Clinico-ResNet + Molecular)
Author: Fadel Batal
Revised: June 2026

CONFIDENCE INTERVAL METHODOLOGY
---------------------------------
Point estimates (risk score and 1/3/5-yr PFS) come from an unregularized Cox
proportional hazards model refit on the full discovery cohort using the original
scalers ("refit_fusion_model"). This removes LASSO shrinkage bias while keeping
all quantities on the same scale.

Survival curves and their 95% confidence bands are derived entirely from the
same model family: the center line is refit_fusion_model's predicted survival
function; the band is the 2.5th-97.5th percentile of 1,000 bootstrap survival
curves. Each bootstrap entry pairs an unregularized Cox model with its own
StandardScaler refit on that bootstrap resample, ensuring the scaling and
fitting steps are consistent within every iteration. At inference time each
bootstrap entry applies its own scaler to the raw risk scores before predicting,
so the CI reflects both coefficient uncertainty and scaling variability.
Percentile-based intervals are used rather than ±1.96×std to respect the [0,1]
bounds of survival probabilities and avoid symmetry assumptions that do not hold
near 0 or 1. Because point estimates and CIs are derived from the same model
family on the same scale, the point estimate is guaranteed to fall within its
own confidence band.
"""

